#!/usr/bin/env python3
"""
da3_relay_node.py — Depth Anything V3 TRT → Canonical Depth Contract Bridge.

Subscribes to the output of the Depth Anything V3 TensorRT ROS 2 node
(github.com/ika-rwth-aachen/ros2-depth-anything-v3-trt) and publishes
the canonical /perception/depth/* topics expected by the rest of the pipeline.

This relay is intentionally minimal: it forwards the 32FC1 depth image,
re-publishes the original camera_info, and produces a TURBO-colourised
visualisation for RViz. The point cloud is generated by the always-on
depth_to_pointcloud_node from the relayed depth image.

Subscribed topics (configurable):
  da3_depth_topic      → sensor_msgs/Image   32FC1 from DA V3 TRT node
  camera_info_topic    → sensor_msgs/CameraInfo (original camera)

Published topics:
  /perception/depth/image_raw    32FC1 metres  RELIABLE  camera_link_optical
  /perception/depth/camera_info  CameraInfo    RELIABLE
  /perception/depth/colorized    bgr8 TURBO    RELIABLE  (RViz only)
"""

import rclpy
from rclpy.node import Node
from rclpy.qos import QoSProfile, ReliabilityPolicy, HistoryPolicy

import numpy as np
import cv2
from cv_bridge import CvBridge

from sensor_msgs.msg import Image, CameraInfo


class Da3RelayNode(Node):
    def __init__(self):
        super().__init__('da3_relay_node')

        # ── Parameters ──────────────────────────────────────────────────────
        self.declare_parameter(
            'da3_depth_topic',
            '/depth_anything_v3/output/depth_image'
        )
        self.declare_parameter(
            'camera_info_topic',
            '/camera/camera_info'
        )
        self.declare_parameter('output_depth_topic', '/perception/depth/image_raw')
        self.declare_parameter('output_info_topic',  '/perception/depth/camera_info')
        self.declare_parameter('output_color_topic', '/perception/depth/colorized')
        self.declare_parameter('output_frame_id',    'camera_link_optical')
        self.declare_parameter('colorize_max_depth', 15.0)

        da3_depth_topic   = self.get_parameter('da3_depth_topic').value
        camera_info_topic = self.get_parameter('camera_info_topic').value
        out_depth_topic   = self.get_parameter('output_depth_topic').value
        out_info_topic    = self.get_parameter('output_info_topic').value
        out_color_topic   = self.get_parameter('output_color_topic').value
        self.out_frame_id = self.get_parameter('output_frame_id').value
        self.colorize_max = float(self.get_parameter('colorize_max_depth').value)

        self.bridge = CvBridge()
        self._latest_camera_info: CameraInfo | None = None

        # ── QoS ─────────────────────────────────────────────────────────────
        sensor_qos = QoSProfile(
            reliability=ReliabilityPolicy.BEST_EFFORT,
            history=HistoryPolicy.KEEP_LAST, depth=1
        )
        reliable_qos = QoSProfile(
            reliability=ReliabilityPolicy.RELIABLE,
            history=HistoryPolicy.KEEP_LAST, depth=10
        )

        # ── Subscribers ──────────────────────────────────────────────────────
        # DA V3 node publishes with default QoS (RELIABLE depth-1); accept
        # either reliability by using BEST_EFFORT on the subscriber side so
        # the subscriber works even if QoS is renegotiated.
        self.depth_sub = self.create_subscription(
            Image, da3_depth_topic, self._on_depth, reliable_qos)
        self.info_sub = self.create_subscription(
            CameraInfo, camera_info_topic, self._on_camera_info, sensor_qos)

        # ── Publishers ───────────────────────────────────────────────────────
        self.depth_pub = self.create_publisher(Image,      out_depth_topic, reliable_qos)
        self.info_pub  = self.create_publisher(CameraInfo, out_info_topic,  reliable_qos)
        self.color_pub = self.create_publisher(Image,      out_color_topic, reliable_qos)

        self.get_logger().info(
            f'[Da3RelayNode] Ready\n'
            f'  DA V3 depth in  ← {da3_depth_topic}\n'
            f'  Camera info in  ← {camera_info_topic}\n'
            f'  depth out       → {out_depth_topic}\n'
            f'  camera_info out → {out_info_topic}\n'
            f'  colorized out   → {out_color_topic}'
        )

    # ── Callbacks ────────────────────────────────────────────────────────────

    def _on_camera_info(self, msg: CameraInfo) -> None:
        self._latest_camera_info = msg

    def _on_depth(self, msg: Image) -> None:
        """Forward 32FC1 depth, re-publish camera_info, generate TURBO colour viz."""
        try:
            # ── Depth passthrough (enforce canonical frame and RELIABLE QoS) ──
            depth_out = Image()
            depth_out.header        = msg.header
            depth_out.header.frame_id = self.out_frame_id
            depth_out.height        = msg.height
            depth_out.width         = msg.width
            depth_out.encoding      = msg.encoding   # 32FC1 passthrough
            depth_out.is_bigendian  = msg.is_bigendian
            depth_out.step          = msg.step
            depth_out.data          = msg.data
            self.depth_pub.publish(depth_out)

            # ── Camera info ────────────────────────────────────────────────
            if self._latest_camera_info is not None:
                info_out = CameraInfo()
                info_out.header           = depth_out.header
                info_out.height           = self._latest_camera_info.height
                info_out.width            = self._latest_camera_info.width
                info_out.distortion_model = self._latest_camera_info.distortion_model
                info_out.d                = self._latest_camera_info.d
                info_out.k                = self._latest_camera_info.k
                info_out.r                = self._latest_camera_info.r
                info_out.p                = self._latest_camera_info.p
                self.info_pub.publish(info_out)

            # ── TURBO colourised visualization (RViz) ──────────────────────
            depth_cv = self.bridge.imgmsg_to_cv2(msg, desired_encoding='32FC1')
            colorized = self._colorize(depth_cv)
            color_msg = self.bridge.cv2_to_imgmsg(colorized, encoding='bgr8')
            color_msg.header = depth_out.header
            self.color_pub.publish(color_msg)

        except Exception as e:
            self.get_logger().error(f'_on_depth error: {e}', throttle_duration_sec=5.0)

    # ── Helpers ───────────────────────────────────────────────────────────────

    def _colorize(self, depth_f: np.ndarray) -> np.ndarray:
        """Convert 32FC1 depth (metres) → bgr8 TURBO for RViz.

        Black = invalid / non-finite. Dark-blue = close. Red/white = far.
        """
        invalid = ~np.isfinite(depth_f) | (depth_f <= 0.0)
        clean   = np.where(invalid, 0.0, depth_f)
        norm    = (
            np.clip(clean, 0.0, self.colorize_max) / self.colorize_max * 255
        ).astype(np.uint8)
        colored = cv2.applyColorMap(norm, cv2.COLORMAP_TURBO)
        colored[invalid] = (0, 0, 0)
        return colored


def main(args=None):
    rclpy.init(args=args)
    node = Da3RelayNode()
    try:
        rclpy.spin(node)
    except KeyboardInterrupt:
        pass
    finally:
        node.destroy_node()
        rclpy.shutdown()


if __name__ == '__main__':
    main()
